package tests_test

import (
	"strconv"
	"testing"
	"time"

	"github.com/emersion/go-smtp"
	"github.com/foxcpp/maddy/internal/testutils"
	"github.com/foxcpp/maddy/tests"
)

func TestIssue327(tt *testing.T) {
	tt.Parallel()
	t := tests.NewT(tt)
	t.AllowFDSharing()
	t.DNS(nil)

	t.Port("smtp")

	be, s := testutils.SMTPServer(tt, "127.0.0.1:0", func(s *smtp.Server) {
		s.LMTP = true
	})
	be.LMTPDataErr = []error{nil, nil}
	defer s.Close()
	t.Env("TEST_TARGET_PORT=" + strconv.Itoa(int(testutils.EffectiveSMTPServerPort(tt, s))))

	t.Config(`
		hostname mx.maddy.test
		tls off
		smtp {env:TEST_ENDPOINT_smtp} {
			deliver_to queue outbound_queue {
				target remote { } # it will fail
				autogenerated_msg_domain maddy.test
				bounce {
					check {
						spf
					}
					deliver_to lmtp tcp://127.0.0.1:{env:TEST_TARGET_PORT}
				}
			}
		}`)
	t.Run(1)
	defer t.Close()

	c := t.Conn("smtp")
	defer c.Close()
	c.SMTPNegotation("client.maddy.test", nil, nil)
	c.Writeln("MAIL FROM:<from@maddy.test>")
	c.ExpectPattern("250 *")
	c.Writeln("RCPT TO:<to1@maddy.test>")
	c.ExpectPattern("250 *")
	c.Writeln("DATA")
	c.ExpectPattern("354 *")
	c.Writeln("From: <from@maddy.test>")
	c.Writeln("To: <to@maddy.test>")
	c.Writeln("Subject: Hello!")
	c.Writeln("")
	c.Writeln("Hello!")
	c.Writeln(".")
	c.ExpectPattern("250 2.0.0 OK: queued")
	c.Writeln("QUIT")
	c.ExpectPattern("221 *")

	for i := 0; i < 5; i++ {
		time.Sleep(1 * time.Second)
		if len(be.Messages) != 0 {
			break
		}
	}

	if len(be.Messages) != 1 {
		t.Fatal("No DSN sent?", len(be.Messages))
	}
}
